export function healthHappyPremium(sex: "male" | "female", age: number, plan: number) {
  if (!Number.isInteger(age) || age < 11 || age > 75) throw new Error("อายุต้องอยู่ระหว่าง 11-75 ปี");
  if (!Number.isInteger(plan) || plan < 0 || plan >= HEALTH_HAPPY_PLANS.length) throw new Error("ไม่พบแผนที่เลือก");
  const range = PREMIUM_RANGES.find(([min, max]) => age >= min && age <= max)!;
  return range[sex === "male" ? 2 : 3][plan];
}
